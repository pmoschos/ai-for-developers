# Define helper function to send prompts to the OpenAI API
def ask(prompt, 
        model = "gpt-4o-mini", 
        system=None, 
        temperature=0, 
        max_tokens=500, 
    client=client) -> str:
    """
    Helper function to send a prompt to an OpenAI-compatible API and get a response.
    Args:
        prompt (str): The question or prompt to ask the model.
        model (str, optional): The model to use for the request. Default is "gpt-4o-mini".
        system (str, optional): An optional system message to provide context to the model.
        temperature (float, optional): The sampling temperature to use for the response. Default is 0.
        max_tokens (int, optional): The maximum number of tokens to generate in the response. Default is 1500.
        client (object, optional): The OpenAI-compatible client to use for the request. Default is openai_client.
    Returns:
        str: The response generated by the model.
    """
    #Validate temperature and default
    if not (0.0 <= temperature <= 1.0):
        print("Temperature must be between 0.0 and 1.0")
        print("Using default temperature of 0.0")
        temperature = 0.0
    #Validate max_tokens and default
    if max_tokens <= 0:
        print("max_tokens must be a positive integer")
        print("Using default max_tokens of 500")
        max_tokens = 500
    # Get client    
    try:
        client = client
    except Exception as e:
        raise ValueError(f"Invalid client provided: {e}")
    
    msgs = []
    if system:
        msgs.append({"role": "system", "content": system})
    msgs.append({"role": "user", "content": prompt})
    r = client.chat.completions.create(
        model=model, 
        messages=msgs,
        temperature=temperature, 
        max_tokens=max_tokens
    )
    return r.choices[0].message.content


def load_cli_config() -> dict:
    """Loads persisted CLI defaults from disk if available.
    Args:
        None
    Returns:
        dict: A configuration dictionary with "client" and "model" keys.    
    """
    config = DEFAULT_CONFIG.copy()

    if not CONFIG_PATH.exists():
        return config

    try:
        stored_config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        console.print(f"[yellow]Ignoring invalid config file at {CONFIG_PATH}: {exc}[/yellow]")
        return config

    if isinstance(stored_config, dict):
        client_name = stored_config.get("client")
        model_name = stored_config.get("model")
        if isinstance(client_name, str):
            config["client"] = client_name
        if isinstance(model_name, str) and model_name.strip():
            config["model"] = model_name.strip()

    return config

def save_cli_config(config: dict) -> None:
    """Persists CLI defaults to disk.
    Args:
        config (dict): The configuration dictionary to save.
    Returns:
        None
    """
    CONFIG_PATH.write_text(json.dumps(config, indent=2), encoding="utf-8")

def get_available_client_names() -> list[str]:
    """Returns the client names that can be used in the current environment.
    Args:
        None
    Returns:
        list[str]: A list of available client names.
    """
    available_clients = ["ollama"]
    if openai_client:
        available_clients.insert(0, "openai")
    return available_clients


def resolve_client(client_name: str) -> OpenAI:
    """Resolves a configured client name to an OpenAI-compatible client instance.
    Args:
        client_name (str): The name of the client to resolve.
    Returns:
        OpenAI: An OpenAI-compatible client instance.
    Raises:
        ValueError: If the client name is unsupported or required API keys are missing.
    """
    normalized_name = client_name.strip().lower()
    if normalized_name == "openai":
        if not openai_client:
            raise ValueError("OPENAI_API_KEY not found. Configure an API key or use the ollama client.")
        return openai_client
    if normalized_name == "ollama":
        return ollama_client
    raise ValueError(f"Unsupported client '{client_name}'. Choose from: {', '.join(get_available_client_names())}.")


def interactive_setup(current_config: dict) -> dict:
    """Prompts the user for default client and model values.
    Args:
        current_config (dict): The current configuration to use as defaults in the prompts.
    Returns:
        dict: A dictionary containing the selected "client" and "model".    
    """
    available_clients = get_available_client_names()
    default_client = current_config.get("client", DEFAULT_CONFIG["client"])
    if default_client not in available_clients:
        default_client = available_clients[0]

    selected_client = Prompt.ask(
        "Select default client",
        choices=available_clients,
        default=default_client,
    )
    selected_model = Prompt.ask(
        "Select default model",
        default=current_config.get("model", DEFAULT_CONFIG["model"]),
    ).strip()

    if not selected_model:
        raise ValueError("Model name cannot be empty.")

    return {"client": selected_client, "model": selected_model}


def run_setup_mode(args: argparse.Namespace) -> None:
    """Handles configuration setup for persisted client/model defaults.
    Args:
        args (argparse.Namespace): The command-line arguments.
    Returns:
        None
    """
    current_config = load_cli_config()
    client_provided = getattr(args, "client_provided", False)
    model_provided = getattr(args, "model_provided", False)

    no_explicit_action = not any((args.interactive, args.show, client_provided, model_provided))
    if no_explicit_action:
        args.show = True

    if args.show:
        console.print(Panel(
            f"[bold]Config file:[/bold] {CONFIG_PATH}\n"
            f"[bold]Default client:[/bold] {current_config['client']}\n"
            f"[bold]Default model:[/bold] {current_config['model']}",
            title="[bold cyan]Current Setup[/bold cyan]",
            border_style="cyan",
        ))
        if not args.interactive and not client_provided and not model_provided:
            return

    if args.interactive:
        next_config = interactive_setup(current_config)
    elif client_provided or model_provided:
        next_config = current_config.copy()
        if client_provided:
            next_config["client"] = args.client.strip().lower()
        if model_provided:
            next_config["model"] = args.model.strip()
    else:
        return

    resolve_client(next_config["client"])
    if not next_config["model"]:
        raise ValueError("Model name cannot be empty.")

    save_cli_config(next_config)
    console.print(f"[bold green]Saved setup to {CONFIG_PATH}[/bold green]")
    console.print(f"[bold green]Default client:[/bold green] {next_config['client']}")
    console.print(f"[bold green]Default model:[/bold green] {next_config['model']}")

