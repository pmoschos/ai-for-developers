def interactive_mode(with_tests_argu: bool,
                     model: str,
                     client_name: str,
                     selected_client: OpenAI):
    """Runs the code generator in interactive mode, prompting the user 
    for input until they choose to exit.
    Args:
        with_tests_argu: Whether to generate tests for the code (True/False)
        model: Model name used for generation
        client_name: Name of the selected client
        selected_client: OpenAI-compatible client instance used for generation
    Returns:
        None
    """
    console.print(Panel(
        "[bold cyan]Code Generator — Interactive Mode[/bold cyan]\n"
        f"Client: [bold]{client_name}[/bold] | Model: [bold]{model}[/bold]\n"
        "Type a description or [bold]'exit'[/bold] to quit.",
        border_style="cyan"
    ))
    
    while True:
        user_input = Prompt.ask("\n[bold]Enter code description[/bold]")
        if user_input.lower() == 'exit':
            console.print("[bold yellow]Exiting interactive mode.[/bold yellow]")
            break
        else:
            description = user_input.strip()
            if description:
                # Generate code response
                result = generate_code(
                    description,
                    with_tests=with_tests_argu,
                    model=model,
                    client=selected_client,
                )
                
                console.print(Panel(
                    Syntax(result['code'], "python", theme="monokai", line_numbers=True),
                    title="[bold green]Generated Code[/bold green]",
                    border_style="green"
                ))
                # If tests were generated, print them as well
                if with_tests_argu and "tests" in result:
                    console.print(Panel(
                        Syntax(result['tests'], "python", theme="monokai", line_numbers=True),
                        title="[bold blue]Generated Tests[/bold blue]",
                        border_style="blue"
                    ))
                # Prompt to save the code to a file
                if Confirm.ask("Save to file?"):
                    filename = Prompt.ask("Enter the filename", default="output.py")
                    filename = validate_filename(filename)
                    save_code(result['code'], filename, result.get('tests'))
                else:
                    console.print("[yellow]Code not saved.[/yellow]")
    
    return None

