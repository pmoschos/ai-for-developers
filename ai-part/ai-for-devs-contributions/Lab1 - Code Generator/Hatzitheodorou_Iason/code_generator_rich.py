def main():

    # Get CLI arguments
    args = define_cli_args()

    if args.command == 'setup':
        run_setup_mode(args)
        return

    if args.setup:
        run_setup_mode(argparse.Namespace(
            client=None,
            model=None,
            show=True,
            interactive=False,
            client_provided=False,
            model_provided=False,
            command='setup',
        ))
        return

    if args.list_ollama_models:
        try:
            models = get_ollama_models()
        except Exception as exc:
            console.print(f"[bold red]Failed to list Ollama models:[/bold red] {exc}")
            return

        if models:
            console.print("[bold green]Available Ollama models:[/bold green]")
            for model in models:
                console.print(Text(" - ") + format_ollama_model_name(model), highlight=False)
        else:
            console.print("[yellow]No Ollama models found.[/yellow]")
        return

    config = load_cli_config()
    client_name = args.client or config['client']
    model_name = args.model or config['model']
    selected_client = resolve_client(client_name)

    positional_description = ' '.join(args.description_text).strip()
    description = args.description or positional_description

    if args.description and positional_description:
        console.print("[bold red]Please provide the description either as positional text or with --description, not both.[/bold red]")
        return

    if args.i:
        interactive_mode(
            with_tests_argu=args.with_tests,
            model=model_name,
            client_name=client_name,
            selected_client=selected_client,
        )
    else:
        if description:
            # Handle the saving logic based on the different save flags and validate                     
            filename = None
            tests_filename = None

            save_mode = (isinstance(args.save, str), isinstance(args.save_tests_only, str), isinstance(args.save_all, str), args.with_tests)
            match save_mode:
                case (True, False, False, _):
                    filename = validate_filename(args.save)
                case (False, True, False, True):
                    tests_filename = validate_filename(args.save_tests_only)
                case (False, False, True, True):
                    filename = validate_filename(args.save_all)
                    tests_filename = filename.replace(".py", "_tests.py")
                case (True, True, False, True):
                    filename = validate_filename(args.save)
                    tests_filename = validate_filename(args.save_tests_only)
                case (_, True, _, False):
                    raise ValueError("Cannot save tests only if --with-tests is not set.")
                case (_, False, True, False):
                    raise ValueError("Cannot save all if --with-tests is not set.")
                case (False, False, False, False):
                    pass
                case _: # Other flags should pass without a check
                    pass 
            
            result = generate_code(description, 
                                with_tests=args.with_tests, 
                                save_filename=filename if filename else None,
                                tests_filename=tests_filename if tests_filename else None,
                                model=model_name,
                                client=selected_client,
                                max_tokens=args.max_tokens, 
                                temperature=args.temperature)
