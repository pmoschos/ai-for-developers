def validate_json_output_payload(output_data: dict) -> None:
    """Validates JSON output payload against the schema.
    Args:
        output_data: The payload to validate before saving.
    Returns:
        None
    Raises:
        ValueError: If payload does not satisfy the schema.
    """
    try:
        validate(instance=output_data, schema=JSON_OUTPUT_SCHEMA)
    except ValidationError as exc:
        field_path = ".".join(str(part) for part in exc.path)
        location = f" at '{field_path}'" if field_path else ""
        raise ValueError(f"Invalid JSON output payload{location}: {exc.message}") from exc


def define_json_output(model_name: str,
                       client_name: str,
                       description: str,
                       temperature: float,
                       max_tokens: int,
                       with_tests: bool,
                       result: dict,
                       filename: str):
    """Save generated output to a schema-validated JSON file.
    Args:
        model_name: The model used for generation.
        client_name: The client used for generation.
        description: The generation prompt description.
        temperature: The sampling temperature used for generation.
        max_tokens: The max token limit used for generation.
        with_tests: Whether tests were requested for generation.
        result: The dictionary containing generated code and optional tests.
        filename: The output JSON filename.
    Returns:
        None
    """
    output_data = {
        "model": model_name,
        "client": client_name,
        "description": description,
        "temperature": temperature,
        "max_tokens": max_tokens,
        "with_tests": with_tests,
        "created_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "code": result.get("code", ""),
    }
    if "tests" in result:
        output_data["tests"] = result["tests"]

    validate_json_output_payload(output_data)

    output_path = Path(filename)
    output_path.write_text(json.dumps(output_data, indent=2), encoding="utf-8")
    console.print(f"[bold green]✓ JSON output saved to {output_path.absolute()}[/bold green]")

    return None

def define_cli_args(argv=None):
    """Defines the command-line arguments for the code generator CLI.
    Args:
        argv (list, optional): A list of command-line arguments to parse.
    Returns:
        argparse.Namespace: Parsed command-line arguments
    """
    argv = sys.argv[1:] if argv is None else argv
    if argv and argv[0] == 'setup':
        setup_argv = argv[1:]
        args = build_setup_parser().parse_args(setup_argv)
        args.client_provided = any(token == '--client' or token.startswith('--client=') for token in setup_argv)
        args.model_provided = any(token == '--model' or token.startswith('--model=') for token in setup_argv)
        return args
    return build_generation_parser().parse_args(argv)

