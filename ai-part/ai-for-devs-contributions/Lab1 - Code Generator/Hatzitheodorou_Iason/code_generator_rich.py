# Helper rich formatting function
def format_ollama_model_name(model_name: str) -> Text:
    """Formats model name as green base + blue variant.
    Args:
        model_name (str): The raw model name to format.
    Returns:
        Text: A rich Text object with the formatted model name."""
    if ":" not in model_name:
        return Text(model_name, style="green")

    base_name, variant = model_name.split(":", 1)
    text = Text()
    text.append(base_name, style="green")
    text.append(f":{variant}", style="blue")
    return text

# Helper function to fetch available Ollama models using the CLI
def get_ollama_models() -> list[str]:
    """Returns available Ollama model names using the Ollama CLI.
    Args:
        None
    Returns:
        list[str]: A list of available Ollama model names.
    """
    result = subprocess.run(
        ["ollama", "list"],
        capture_output=True,
        text=True,
        check=True,
        encoding="utf-8",
    )
    lines = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    if len(lines) <= 1:
        return []
    models = []
    for line in lines[1:]:
        parts = line.split()
        if parts:
            models.append(parts[0])
    return models

